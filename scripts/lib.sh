#!/usr/bin/env bash
# lib.sh — the checks cargo does not already do, defined once.
#
# Each check writes neutral records to stdout, one per line:
#
#     rule<TAB>level<TAB>path<TAB>line<TAB>message[<TAB>key]
#
# `key` is optional and exists for one reason: a fingerprint is
# `rule:path:line`, and a check whose findings all land on the same line --
# alias_drift, every record of which is `.cargo/config.toml:1` -- would have
# them collide and dedup down to one. Where a location can hold more than one
# finding of the same rule, the key disambiguates. Same mechanism lints-check
# already uses for `lint-missing`.
#
# gate.sh renders them for humans, findings.sh renders them as JSONL. Nothing
# in here knows about either format — that is the whole point. Define a check
# once, render it twice.
#
# Sourced, never executed directly.

# This checkout's root, so a check can reach the canonical config it compares
# against. Set here rather than by each caller: lib.sh is the only file that
# knows it lives one directory down from it.
RQ_DIR="${RQ_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

# ── ai_lint <file...> ────────────────────────────────────────────────────────
# Residue that a compiler cannot see. Deliberately three rules, not four:
# clippy::todo, clippy::unimplemented and clippy::unreachable already cover stub
# macros (verified on a probe crate), so a stub-macro rule here would just
# double-report.
#
# Every rule pipeline ends in `|| true`, and that is load-bearing: grep exits 1
# when a rule does not match, which is the normal case. Callers run this under
# `set -euo pipefail` inside a process substitution, so an unguarded non-match
# would kill the subshell and silently skip every later rule and every later
# file. Same for god_files and dup_deps below — `grep` there exits 1 on the
# healthy case, a workspace with no duplicate versions.
ai_lint() {
  local f
  for f in "$@"; do
    case "$f" in
      target/*|*/target/*|*.pb.rs|*_generated.rs) continue ;;
    esac
    [ -f "$f" ] || continue
    head -5 "$f" 2>/dev/null | grep -qE '^(//|//!) *(@generated|Code generated|Generated by)' && continue

    grep -nHE '(TODO|FIXME|XXX)\((claude|ai|bot|gpt|assistant|copilot|codex)\b' "$f" 2>/dev/null \
      | _rec agent-todo error 'agent-tagged TODO — give it a real owner or open an issue' || true
    grep -nHE '//.*\b([Aa]s requested|[Pp]er your request|[Aa]s you (asked|requested|wanted)|[Ii]n response to your request)\b' "$f" 2>/dev/null \
      | _rec ai-self-ref error 'prompt artifact — the comment is talking to the agent' || true
    grep -nHE '//[[:space:]]*(REMOVED|PREVIOUSLY|WAS):[[:space:]]' "$f" 2>/dev/null \
      | _rec diff-relic error 'diff relic — belongs in commit history, not source' || true
  done
}

# _rec <rule> <level> <message>  — turn `path:line:text` on stdin into records.
_rec() {
  local rule="$1" level="$2" msg="$3" line path lineno
  while IFS= read -r line; do
    [ -z "$line" ] && continue
    path="${line%%:*}"; lineno="${line#*:}"; lineno="${lineno%%:*}"
    printf '%s\t%s\t%s\t%s\t%s\n' "$rule" "$level" "$path" "$lineno" "$msg"
  done
}

# ── comment_lint <file...> ───────────────────────────────────────────────────
# The comment budget. `missing_docs` and `rustdoc -D warnings` push doc
# comments up; nothing pushed non-doc `//` down, and an agent that cannot
# delete is rewarded for narrating. clippy has no comment-volume lint and no
# credible Rust tool for one exists, so this is ours: three rules, one awk pass
# per file, no new tool and no second compile.
#
#   commented-out-code  error    a `//` line that is Rust, not prose
#   comment-block       warning  CAP_COMMENT_RUN consecutive non-doc `//`
#   comment-ratio       warning  non-doc `//` over CAP_COMMENT_RATIO% of code
#
# Only the first is an error, because it is the only one that is never right:
# dead code in a comment is worse than dead code, since the compiler cannot
# even tell you it rotted. The other two are judgement calls -- a 40-line
# comment that earns its keep is the house style in this very repo -- so they
# ride with the soft caps and never fail a build.
#
# `///` and `//!` are outside all three. `missing_docs` and rustdoc govern
# those, and counting them here would be two gates pulling one line both ways.
#
# The error rule matches SHAPE, not keywords. `// let the caller decide` and
# `// use the first one that works` are prose that opens with a Rust keyword,
# so every pattern pairs a declaration head with a code terminator. A bare call
# statement -- `// foo(bar);`, which is also what quoted C looks like inside a
# SAFETY block -- is deliberately not a pattern: a false positive here fails
# the gate on correct source.
comment_lint() {
  local f
  for f in "$@"; do
    case "$f" in
      target/*|*/target/*|*.pb.rs|*_generated.rs) continue ;;
    esac
    [ -f "$f" ] || continue
    head -5 "$f" 2>/dev/null | grep -qE '^(//|//!) *(@generated|Code generated|Generated by)' && continue

    awk -v path="$f" \
        -v caprun="${CAP_COMMENT_RUN:-15}" \
        -v capratio="${CAP_COMMENT_RATIO:-40}" '
      function flush() {
        if (run >= caprun)
          printf "comment-block\twarning\t%s\t%d\t%d consecutive comment lines, over the %d cap\n", \
                 path, runstart, run, caprun
        run = 0
      }
      {
        line = $0
        sub(/^[ \t]+/, "", line); sub(/[ \t]+$/, "", line)

        if (line ~ /^\/\/\// || line ~ /^\/\/!/) { if (run) flush(); next }

        if (line ~ /^\/\//) {
          if (run == 0) runstart = NR
          run++; cmt++
          if (line ~ /^\/\/[ \t]*let[ \t]+[a-zA-Z_(][^=]*=.*;$/ \
           || line ~ /^\/\/[ \t]*(pub[ \t]+)?(async[ \t]+)?fn[ \t]+[a-zA-Z_][A-Za-z0-9_]*.*\{$/ \
           || line ~ /^\/\/[ \t]*(pub[ \t]+)?(struct|enum|trait|impl|mod)[ \t]+[A-Za-z_][A-Za-z0-9_]*.*[{;]$/ \
           || line ~ /^\/\/[ \t]*(pub[ \t]+)?(const|static)[ \t]+[A-Z_][A-Z0-9_]*[ \t]*:.*;$/ \
           || line ~ /^\/\/[ \t]*use[ \t]+[a-z_][A-Za-z0-9_]*(::[A-Za-z0-9_{}*, ]+)+;$/ \
           || line ~ /^\/\/[ \t]*#\[[a-z_][a-z_0-9]*(\(.*\))?\]$/)
            printf "commented-out-code\terror\t%s\t%d\tcommented-out code — delete it, git remembers\n", \
                   path, NR
          next
        }

        # A run is ended by the line after it, so a file that ends inside its
        # own banner needs the END flush too.
        if (run) flush()
        if (line != "") code++
      }
      END {
        if (run) flush()
        # A floor as well as a cap: a 6-line stub under a 4-line header is 66%
        # and says nothing worth saying.
        if (code >= 50 && cmt * 100 > capratio * code)
          printf "comment-ratio\twarning\t%s\t1\t%d comment lines to %d code (%d%%), over the %d%% cap\n", \
                 path, cmt, code, int(cmt * 100 / code), capratio
      }
    ' "$f" || true
  done
}

# ── god_files ────────────────────────────────────────────────────────────────
# The one structural cap clippy has no opinion about. Complexity is NOT here:
# clippy::cognitive_complexity plus cognitive-complexity-threshold owns that,
# enforced by the lint gate with no second compile and no extra tool.
#
# Counts CODE lines -- neither blank nor comment. It was `wc -l`, so a 74-line
# comment block spent 74 lines of a 500-line budget and the one check meant to
# bound file size was partly measuring prose. `comment-ratio` bounds the other
# half; together they say "too big" and "mostly talking" separately, which one
# `wc -l` never could.
god_files() {
  local cap="${CAP_LOC:-500}"
  # `-c core.quotePath=` keeps a non-ASCII path as its own bytes instead of
  # C-quoting it into "cr\303\251ate.rs", which names no file on disk.
  #
  # FILENAME rather than a `wc`-style count column. That also retires the old
  # note about paths with spaces: awk is handed each name by xargs and never
  # has to parse one back out of a padded line.
  #
  # The single-quoted payload below is an awk program. shellcheck only
  # recognises one when `awk` is the command itself, not when it is an
  # argument to xargs, so it reads `$0` as a shell expansion that failed to
  # expand. It is not one.
  # shellcheck disable=SC2016
  git -c core.quotePath= ls-files -- '*.rs' \
    | grep -vE '(^|/)(target|vendor)/|(^|/)(tests|benches|examples)/|\.pb\.rs$|_generated\.rs$' \
    | tr '\n' '\0' | xargs -0 awk -v cap="$cap" '
        function emit() {
          if (file != "" && n > cap)
            printf "god-file\twarning\t%s\t1\t%d code lines over the %d cap\n", file, n, cap
        }
        FNR == 1 { if (NR > 1) emit(); file = FILENAME; n = 0 }
        {
          line = $0; sub(/^[ \t]+/, "", line)
          if (line != "" && line !~ /^\/\//) n++
        }
        END { emit() }' 2>/dev/null \
    || true
}

# ── dup_deps ─────────────────────────────────────────────────────────────────
# Two versions of a crate means two copies in the binary, two build scripts
# running, and a type mismatch the moment either appears in a public signature.
# Offline — the lockfile is the source of truth and a gate must not reach the
# network.
dup_deps() {
  command -v cargo >/dev/null 2>&1 || return 0
  [ -f Cargo.lock ] || return 0
  cargo tree --workspace --duplicates --edges normal --offline 2>/dev/null \
    | grep -E '^[a-zA-Z0-9_.-]+ v[0-9]' | awk '{print $1}' | sort -u \
    | awk '{ printf "duplicate-dep\twarning\tCargo.lock\t1\t%s resolves to more than one version\n", $1 }' \
    || true
}

# ── alias_drift ──────────────────────────────────────────────────────────────
# `sync-config` installs `.cargo/config.toml` behind `creates:`, because that
# file is where a consumer keeps its own `[build] rustflags` and `[target.*]
# linker`, and writing ours over it is data loss rather than a sync. But
# `creates:` is write-once: installed on day one, never reconciled, and the
# preset's advice to merge the rest by hand is advice, not a gate. Measured
# before this check existed, four of five consumers that had the file were
# still on a copy predating `--no-tests=warn`, and nothing had ever said so.
#
# So: the same answer as the lint block, for the same reason -- where we must
# not mutate, we enforce. A line compare, not a TOML parse. The keys are ours
# and we write them one per line, so a parser buys nothing here.
alias_drift() {
  local canon="${RQ_DIR:-}/aliases.toml" cfg=".cargo/config.toml"
  [ -f "$canon" ] || return 0
  [ -f "$cfg" ] || return 0

  # The `[alias]` table only. `[env]` carries RUSTDOCFLAGS, which a consumer
  # has a legitimate reason to extend.
  awk '/^\[alias\]/{a=1;next} /^\[/{a=0} a && /^[a-zA-Z0-9_-]+[ \t]*=/{print}' "$canon" \
  | while IFS= read -r want; do
      key="${want%%=*}"; key="$(printf '%s' "$key" | tr -d ' \t')"
      [ -n "$key" ] || continue
      val="$(printf '%s' "${want#*=}" | tr -d ' \t')"
      have="$(awk -v k="$key" '/^\[alias\]/{a=1;next} /^\[/{a=0}
                a && $0 ~ "^"k"[ \t]*=" {sub(/^[^=]*=/,"");print;exit}' "$cfg" | tr -d ' \t')"
      if [ -z "$have" ]; then
        printf 'alias-drift\twarning\t%s\t1\tcargo alias "%s" is missing — rq/sync-config prints the canonical block\t%s\n' \
          "$cfg" "$key" "$key"
      elif [ "$have" != "$val" ]; then
        printf 'alias-drift\twarning\t%s\t1\tcargo alias "%s" differs from the canonical one\t%s\n' \
          "$cfg" "$key" "$key"
      fi
    done
}

# ── staged_rs / tracked_rs ───────────────────────────────────────────────────
staged_rs()  { git diff --cached --name-only --diff-filter=ACMR -- '*.rs' 2>/dev/null; }
tracked_rs() { git ls-files -- '*.rs' 2>/dev/null; }

# ── py_toml ──────────────────────────────────────────────────────────────────
# Print the first python on this box that can actually parse TOML, or fail.
#
# A bare `python3` is a PATH lookup, and on macOS that lookup is rigged against
# us: `tomllib` is stdlib only from 3.11, /usr/bin/python3 is 3.9, and
# /usr/libexec/path_helper — run from /etc/zprofile on every login shell —
# rebuilds PATH with /etc/paths ahead of everything, so /usr/bin always
# outranks Homebrew no matter what order was inherited. Seed it with
# `/opt/homebrew/bin:/usr/bin` and it hands back /usr/bin first. The result was
# a gate that failed on the one interpreter in the fleet that cannot do the
# job, on a machine with 3.14 installed two directories away, and said so only
# by ModuleNotFoundError traceback.
#
# So: probe by capability, never by name. `python3` is tried first so a box
# that has already put the right one on PATH — Arch, Ubuntu 24.04 — pays
# nothing and the fleet stays uniform. `tomli` is the pre-3.11 backport and is
# accepted; the callers import it under the same name.
#
# The absolute candidates at the tail are for a PATH stripped down past the
# point where any of the names resolve -- a systemd unit, a launchd job, a
# container with the bare defaults. They cost one failed stat each on a box
# that never needs them.
py_toml() {
  local c
  for c in "${RQ_PYTHON:-}" python3 python3.14 python3.13 python3.12 python3.11 python \
           /opt/homebrew/bin/python3 /usr/local/bin/python3 \
           /home/linuxbrew/.linuxbrew/bin/python3; do
    [ -n "$c" ] || continue
    command -v "$c" >/dev/null 2>&1 || continue
    if "$c" -c 'import tomllib' >/dev/null 2>&1 \
    || "$c" -c 'import tomli'   >/dev/null 2>&1; then
      printf '%s\n' "$c"
      return 0
    fi
  done
  return 1
}
